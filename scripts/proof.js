// Regenerates Phase evidence: runs every scenario through the real CLI, a determinism
// double-run, bot playthroughs and a perf measurement, then writes docs/proof/<phase>/.
//   npm run proof            (current phase, see package.json)
//   node scripts/proof.js phase-N
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { cpus, platform, release, totalmem } from 'node:os';
import { join } from 'node:path';
import { SCENARIOS } from '../tests/scenarios.js';
import { ROOT, runCli, runScenario } from '../tests/harness.js';
import { playBot } from './bot.js';

const phase = process.argv[2] || 'phase-3';
const dir = join(ROOT, 'docs', 'proof', phase);
rmSync(join(dir, 'scenarios'), { recursive: true, force: true });
rmSync(join(dir, 'playthrough'), { recursive: true, force: true });
mkdirSync(dir, { recursive: true });

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: ROOT, encoding: 'utf8' }).trim();
  const dirty = execSync('git status --porcelain -- src game.contract.json', { cwd: ROOT, encoding: 'utf8' }).trim();
  if (dirty) commit += ' (+ uncommitted src changes)';
} catch {}

const md = [];
const rel = (p) => p.replace(ROOT, '.').replaceAll('\\', '/');
md.push(`# Evidence — ${phase}`, '');
md.push('> Generated by `npm run proof` (scripts/proof.js). Do not edit by hand.', '');
md.push(`- Code: commit \`${commit}\``);
md.push(`- Machine: ${platform()} ${release()}, ${cpus()[0]?.model?.trim()} x${cpus().length}, ${(totalmem() / 2 ** 30).toFixed(1)} GB RAM, Node ${process.version}`, '');

// 1. Scenarios
md.push('## 1. Headless scenarios (real CLI)', '', '| Scenario | Req | What is checked | Result |', '|---|---|---|---|');
let pass = 0;
const details = [];
for (const sc of SCENARIOS) {
  const sdir = join(dir, 'scenarios', sc.name);
  const r = runScenario(sc, sdir);
  // Keep proof small: full output for short runs, otherwise head + events + tail.
  const outPath = join(sdir, 'out.jsonl');
  if (r.lines.length > 400) writeFileSync(outPath, [...r.lines.slice(0, 50), ...r.lines.filter((l) => l.includes('"event"')), ...r.lines.slice(-50)].join('\n') + '\n');
  const ok = r.results.every((x) => x.pass);
  if (ok) pass++;
  md.push(`| [${sc.name}](scenarios/${sc.name}/) | ${sc.req} | ${sc.what.replaceAll('|', '/')} | ${ok ? 'PASS' : '**FAIL**'} |`);
  details.push(`### ${sc.name} — ${ok ? 'PASS' : 'FAIL'}`, '', '```', r.cmd, '```', ...r.results.map((x) => `- ${x.pass ? '✔' : '✘'} ${x.msg}`), '');
}
md.push('', `**${pass}/${SCENARIOS.length} scenarios pass.** Files per scenario: \`scenario.json\`, \`inputs.json\`, \`out.jsonl\` (long runs trimmed to head + all events + tail).`, '');

// 2. Determinism
md.push('## 2. Determinism (same seed + inputs, two runs)', '');
const pdir = join(dir, 'playthrough');
mkdirSync(pdir, { recursive: true });
const bot1 = playBot(1);
const inputs1 = join(pdir, 'bot-seed1.inputs.json');
writeFileSync(inputs1, JSON.stringify({ frames: bot1.frames }) + '\n');
const runA = join(pdir, 'run-a.jsonl');
const runB = join(pdir, 'run-b.jsonl');
for (const o of [runA, runB]) runCli(['--seed', '1', '--night', '1', '--inputs', inputs1, '--ticks', '18000', '--out', o]);
const a = readFileSync(runA, 'utf8');
const b = readFileSync(runB, 'utf8');
md.push('```', `node src/headless.js --seed 1 --night 1 --inputs ${rel(inputs1)} --ticks 18000 --out run-a.jsonl  (and run-b.jsonl)`, '```');
md.push(`- run-a: ${a.split('\n').length - 1} lines, ${a.length} bytes; run-b: ${b.split('\n').length - 1} lines, ${b.length} bytes`);
md.push(`- Byte-identical: **${a === b ? 'YES' : 'NO'}**`, '');
rmSync(runB);

// 3. Playthroughs
md.push('## 3. Full-night playthroughs (default level, greedy bot inputs replayed via CLI)', '', '| Night | Seed | End line | game_over | Lanterns lit |', '|---|---|---|---|---|');
const maxTicks = { 1: 18000, 2: 19800, 3: 21600 };
for (const [night, seeds] of [[1, [1, 2, 3, 4, 5]], [2, [1, 2, 3]], [3, [1, 2, 3]]]) {
  for (const seed of seeds) {
    const bot = night === 1 && seed === 1 ? bot1 : playBot(seed, night);
    const inp = join(pdir, `bot-n${night}-seed${seed}.inputs.json`);
    writeFileSync(inp, JSON.stringify({ frames: bot.frames }) + '\n');
    const out = join(pdir, `bot-n${night}-seed${seed}.events.jsonl`);
    runCli(['--seed', String(seed), '--night', String(night), '--inputs', inp, '--ticks', String(maxTicks[night]), '--out', out]);
    const lines = readFileSync(out, 'utf8').trim().split('\n');
    const go = lines.map((l) => JSON.parse(l)).find((o) => o.name === 'game_over');
    const lit = lines.filter((l) => l.includes('"lantern_lit"')).length;
    md.push(`| ${night} | ${seed} | \`${lines.at(-1)}\` | ${go ? JSON.stringify(go.data) : '-'} | ${lit} |`);
    // keep only events + end for size
    writeFileSync(out, lines.filter((l) => !l.includes('"snapshot"')).join('\n') + '\n');
  }
}
rmSync(runA);
md.push('');

// 4. Performance
md.push('## 4. Performance (headless)', '');
const perf = [];
for (let i = 0; i < 3; i++) {
  const t0 = process.hrtime.bigint();
  runCli(['--seed', '9', '--night', '3', '--ticks', '21600', '--out', join(pdir, 'perf.jsonl')]);
  perf.push(Number(process.hrtime.bigint() - t0) / 1e6);
}
rmSync(join(pdir, 'perf.jsonl'));
md.push(`- Night 3, up to 21600 ticks (contract limit: a full night in <= 30 s), default level, snapshot every 10: ${perf.map((x) => `${x.toFixed(0)} ms`).join(', ')} (includes Node start-up)`, '');

md.push('## 5. Scenario details', '', ...details);
writeFileSync(join(dir, 'headless-report.md'), md.join('\n') + '\n');
console.log(`${phase}: ${pass}/${SCENARIOS.length} scenarios pass, deterministic=${a === b}. Report: ${rel(join(dir, 'headless-report.md'))}`);
if (pass !== SCENARIOS.length || a !== b) process.exitCode = 1;
